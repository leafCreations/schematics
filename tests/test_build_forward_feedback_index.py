def test_parse_forward_feedback_items_extracts_fields():
    text = _gc5_body()
    items = parse_forward_feedback_items(text)
    assert len(items) == 6
    governance = next(item for item in items if item.category == "Governance")
    assert governance.question.startswith("Should registry yaml")
    assert governance.risk_level == 4
    assert governance.impact_scope == "system-wide"
    assert governance.importance == "Primary"
    assert governance.mitigation is not None


