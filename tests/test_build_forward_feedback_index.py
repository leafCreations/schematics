GC5_ITEM = """
- **Question:** Should registry yaml paths stay schema-internal?
  **Risk Level:** 4 | **Priority:** High | **Importance:** Primary
  **Impact Scope:** system-wide
  **References:** sig:forward-feedback-index
  **Mitigation:** Extend _SCHEMA_INTERNAL_PATHS in same PR.
  **Detail:** Parity checks fail when index paths land in AGENTS table.
"""


def _gc5_body(*, codebase_scope: str = "local", codebase_risk: int = 2) -> str:
    governance = GC5_ITEM
    low = """
- **Question:** Low-priority skill question?
  **Risk Level:** 2 | **Priority:** Low
  **Impact Scope:** local
  **References:** sig:test
"""
    codebase = f"""
- **Question:** Codebase ranking question?
  **Risk Level:** {codebase_risk} | **Priority:** Medium | **Importance:** Secondary
  **Impact Scope:** {codebase_scope}
  **References:** sig:codebase-q
"""
    categories = (
        ("Governance", governance),
        ("Skill", low),
        ("Rule", low),
        ("Codebase", codebase),
        ("Prompt pattern", low),
        ("Routing", low),
    )
    sections = [f"### {name}\n{body.strip()}" for name, body in categories]
    return "## Forward-looking feedback (2026-06-27)\n\n" + "\n\n".join(sections) + "\n"


def _write_closed_card(
    done_dir: Path,
    name: str,
    *,
    body: str,
    labels: str = '["agent"]',
    completed_at: str = "2026-06-27T20:00:00.000Z",
) -> Path:
    path = done_dir / name
    path.write_text(
        "---\n"
        f"labels: {labels}\n"
        f'completedAt: "{completed_at}"\n'
        "epic: ForwardFeedbackRegistry\n"
        "---\n\n"
        "## Lessons captured (2026-06-27)\n\n"
        "- lesson bullet\n\n"
        f"{body}",
        encoding="utf-8",
    )
    return path


