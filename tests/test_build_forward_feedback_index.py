def _write_feedback_card(
    directory: Path,
    name: str,
    *,
    body: str = FEEDBACK_CARD_BODY,
    labels: str = '["feedback"]',
    completed_at: str | None = None,
) -> Path:
    completed_line = f'completedAt: "{completed_at}"\n' if completed_at else ""
    path = directory / name
    path.write_text(
        "---\n"
        f"labels: {labels}\n"
        f"{completed_line}"
        'created: "2026-06-29T20:00:00.000Z"\n'
        "---\n\n"
        f"{body}",
        encoding="utf-8",
    )
    return path


