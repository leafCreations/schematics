def _duplicate_question_body(question: str) -> str:
    item = f"""
- **Question:** {question}
  **Risk Level:** 3 | **Priority:** Medium
  **Impact Scope:** local
  **References:** sig:test
"""
    return "## Forward-looking feedback (2026-06-27)\n\n### Governance\n" + item.strip() + "\n"


def test_build_index_marks_duplicate_question_fingerprints(ff_features):
    repo_root, done = ff_features
    shared = "Should duplicate questions link with duplicate_of?"
    _write_closed_card(done, "card-a.md", body=_duplicate_question_body(shared))
    _write_closed_card(done, "card-b.md", body=_duplicate_question_body(shared))
    payload, warnings = build_index(repo_root=repo_root)
    assert len(payload["items"]) == 2
    canonical = next(row for row in payload["items"] if row["source_card"].endswith("card-a.md"))
    duplicate = next(row for row in payload["items"] if row["source_card"].endswith("card-b.md"))
    assert "duplicate_of" not in canonical
    assert duplicate["duplicate_of"] == canonical["id"]
    assert len(warnings) == 1
    assert "duplicate_of" in warnings[0]


